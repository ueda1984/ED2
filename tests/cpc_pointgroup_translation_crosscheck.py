#!/usr/bin/env python3
"""Independent translation + point-group physical regression for ED2.

Validates site-permutation characters, Burnside dimensions, explicit projected
Hamiltonians, and the native ED2 spectra. Only one-dimensional little-group
irreps are tested; C4v's two-dimensional E irrep is explicitly not claimed.
The pre-existing ED2 L1..L6 cyclic-generator interface is reused, not extended.
"""
import argparse
from collections import defaultdict
import hashlib
import itertools
import json
import math
import os
from pathlib import Path
import re
import subprocess
import tempfile

import numpy as np


def permutation(n, name):
    def transform(i):
        if name == "translate":
            return (i + 1) % n
        x, y = i % n, i // n
        if name == "tx":
            return (x + 1) % n + n * y
        if name == "ty":
            return x + n * ((y + 1) % n)
        if name == "r90":
            return (-y) % n + n * x
        if name == "r180":
            return (-x) % n + n * ((-y) % n)
        if name == "mirror":
            return x + n * ((-y) % n)
        if name == "invert":
            return (-i) % n
        raise ValueError(name)
    total = n if name in ("translate", "invert") else n * n
    return tuple(transform(i) for i in range(total))


def geometry(kind, n):
    if kind == "ring":
        nearest = [(i, (i + 1) % n, 1., .77) for i in range(n)]
        second = [(i, (i + 2) % n, .31, .19) for i in range(n)]
        return nearest + second
    def idx(x, y):
        return x % n + n * (y % n)
    # Spin-1/2 J1-J2 XXZ model. Both diagonals preserve C4v.
    bonds = []
    for y in range(n):
        for x in range(n):
            for dx, dy, xy, zz in ((1, 0, 1., .77), (0, 1, 1., .77),
                                  (1, 1, .31, .19), (1, -1, .31, .19)):
                bonds.append((idx(x, y), idx(x + dx, y + dy), xy, zz))
    return bonds


def generators(kind, n, momentum, irrep):
    if kind == "ring":
        (k,) = momentum
        if k not in (0, n // 2):
            raise ValueError("Inversion belongs to the momentum little group only at k=0 or pi")
        gens = [("translate", n, k)]
        if irrep is not None:
            gens.append(("invert", 2, irrep))
    else:
        kx, ky = momentum
        gens = [("tx", n, kx), ("ty", n, ky)]
        if irrep is not None:
            r, s = irrep
            if momentum in ((0, 0), (n // 2, n // 2)):
                gens += [("r90", 4, 2 * r), ("mirror", 2, s)]
            elif momentum == (n // 2, 0):
                # X: 90-degree rotations leave the momentum sector.
                # Its valid little group is C2v, generated by C2 and a mirror.
                gens += [("r180", 2, r), ("mirror", 2, s)]
            else:
                raise ValueError("Unsupported point-group little group for momentum")
    return [(permutation(n, op), order, character, op) for op, order, character in gens]


def group_elements(gens):
    elements = []
    signatures = set()
    nsites = len(gens[0][0])
    for exps in itertools.product(*(range(order) for _, order, _, _ in gens)):
        p = list(range(nsites))
        # Matches ED2: inner translations act after the outer point operations.
        for (g, _, _, _), exp in zip(reversed(gens), reversed(exps)):
            for _ in range(exp):
                p = [g[x] for x in p]
        phase = sum(m * e / order for (_, order, m, _), e in zip(gens, exps))
        character = math.cos(2. * math.pi * phase)
        if abs(abs(character) - 1.) > 1e-10:
            raise AssertionError("This regression requires real 1D characters")
        character = int(round(character))
        signature = tuple(p)
        if signature in signatures:
            raise AssertionError("Generators do not enumerate distinct group elements")
        signatures.add(signature)
        elements.append((signature, character))
    assert len(elements) == math.prod(g[1] for g in gens)
    return elements


def map_mask(mask, perm):
    mapped = 0
    while mask:
        low = mask & -mask
        mapped |= 1 << perm[low.bit_length() - 1]
        mask ^= low
    return mapped


def states_of(nsites, ndown):
    return [sum(1 << i for i in combo) for combo in itertools.combinations(range(nsites), ndown)]


def invariant_bonds(bonds, gens):
    original = sorted((min(i, j), max(i, j), xy, zz) for i, j, xy, zz in bonds)
    if len(set(original)) != len(original):
        raise AssertionError("Duplicate physical bonds")
    for perm, _, _, op in gens:
        moved = sorted((min(perm[i], perm[j]), max(perm[i], perm[j]), xy, zz)
                       for i, j, xy, zz in bonds)
        assert original == moved, ("Hamiltonian does not commute with", op)


def reference(masks, gens, bonds):
    elements = group_elements(gens)
    index = {mask: i for i, mask in enumerate(masks)}
    group_size = len(elements)
    trace_sum = 0
    for perm, chi in elements:
        trace_sum += chi * sum(map_mask(mask, perm) == mask for mask in masks)
    assert trace_sum % group_size == 0, ("Noninteger Burnside trace", trace_sum, group_size)
    dim = trace_sum // group_size
    assert dim >= 0
    visited = set()
    cols = []
    for mask in masks:
        if mask in visited:
            continue
        amplitudes = defaultdict(int)
        for perm, chi in elements:
            amplitudes[map_mask(mask, perm)] += chi
        visited.update(amplitudes)
        norm = math.sqrt(sum(v * v for v in amplitudes.values()))
        if norm < 1e-9:
            continue
        column = np.zeros(len(masks))
        for target, weight in amplitudes.items():
            column[index[target]] = weight / norm
        cols.append(column)
    assert len(cols) == dim, ("Projected dimension != Burnside", len(cols), dim)
    q = np.column_stack(cols) if cols else np.empty((len(masks), 0))
    if dim == 0:
        return dict(dimension=0, energies=[], q=q)
    assert np.linalg.norm(q.T @ q - np.eye(dim)) < 1e-9
    for perm, order, m, op in gens:
        phase = int(round(math.cos(2 * math.pi * m / order)))
        dest = np.fromiter((index[map_mask(x, perm)] for x in masks), dtype=int, count=len(masks))
        transformed = np.zeros_like(q)
        transformed[dest, :] = q
        assert np.linalg.norm(transformed - phase * q) < 1e-8, ("Character mismatch", op)

    hq = np.zeros_like(q)
    for i, j, xy, zz in bonds:
        ni = np.fromiter(((mask >> i) & 1 for mask in masks), dtype=np.int8, count=len(masks))
        nj = np.fromiter(((mask >> j) & 1 for mask in masks), dtype=np.int8, count=len(masks))
        hq += (zz * (.5 - ni) * (.5 - nj))[:, None] * q
        selected = np.flatnonzero(ni != nj)
        destination = [index[masks[t] ^ (1 << i) ^ (1 << j)] for t in selected]
        hq[destination, :] += (.5 * xy) * q[selected, :]
    reduced = q.T @ hq
    assert np.linalg.norm(reduced - reduced.T) < 1e-9
    # H must preserve the representation: not just the energy of PHP.
    assert np.linalg.norm(hq - q @ reduced) < 2e-8, "Hamiltonian leaks outside irrep"
    return dict(dimension=dim, energies=np.linalg.eigvalsh(reduced).tolist(), q=q)


def make_input(root, kind, n, ndown, gens, bonds, alg):
    root.mkdir(parents=True, exist_ok=False)
    nsites = n if kind == "ring" else n * n
    (root / "spins.dat").write_text("0.5\n" * nsites)
    (root / "caps.dat").write_text("1\n" * nsites)
    (root / "fields.dat").write_text("")
    (root / "bonds.dat").write_text("".join(
        f"{i+1} {j+1} {xy:.15g} {xy:.15g} {zz:.15g} 0 0 0 0 0 0\n"
        for i, j, xy, zz in bonds))
    params = [
        f"NOS={nsites},NODmin={ndown},NODmax={ndown},",
        f"NO_one=0,NO_two={len(bonds)},ALG={alg},wk_dim=-1,MNTE=-1,",
        "FILE_xyz_dm_gamma='bonds.dat',FILE_hvec='fields.dat',",
        "FILE_spin='spins.dat',FILE_NODmax='caps.dat',",
        "OUTDIR='./',FILE_wf='./',wr_wf=0,re_wf=0,cal_lm=0,cal_cf=0,"]
    for d in range(6):
        if d < len(gens):
            perm, period, character, _ = gens[d]
            filename = f"perm{d+1}.dat"
            (root / filename).write_text("".join(f"{i+1}\n" for i in perm))
            params.append(f"L{d+1}={period},M{d+1}={character},FILE_S{d+1}='{filename}',")
        else:
            params.append(f"L{d+1}=1,M{d+1}=0,")
    (root / "input.dat").write_text(
        "&input_parameters\n" + "\n".join(params) + "\n/\n"
        "&input_lancz\nlnc_ene_conv=1d-11,minitr=4,maxitr=300,itrint=3\n/\n"
        "&input_TRLan\nNOE=2,NOK=3,NOM=8,maxitr=300,"
        "lnc_ene_conv=1d-11,i_vec_min=1,i_vec_max=1\n/\n")


def execute(exe, root, expected, alg=3, mode="legacy", threads=1):
    env = dict(os.environ, OMP_NUM_THREADS=str(threads), OMP_DYNAMIC="FALSE",
               OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1", ED2_RNG_SEED="1984",
               ED2_DIAGNOSTICS="diagnostics.txt", ED2_RESIDUAL_ATOL="1e-8")
    env.pop("ED2_LANCZOS_TWO_STAGE", None)
    if mode == "two-stage":
        env["ED2_LANCZOS_TWO_STAGE"] = "1"
    with (root / "input.dat").open("rb") as inp, (root / "stdout.log").open("wb") as log:
        cp = subprocess.run([str(exe)], cwd=root, stdin=inp, stdout=log,
                            stderr=subprocess.STDOUT, env=env, timeout=90)
    output = (root / "stdout.log").read_text(errors="replace")
    assert cp.returncode == 0, (root, cp.returncode, output[-2200:])
    found = re.findall(r"THS\\(k\\)\\s*=\\s*(\\d+)", output)
    assert len(found) == 1 and int(found[0]) == expected["dimension"], (root, found, expected["dimension"])
    values = [float(line.split()[-1].replace("D", "E"))
              for line in (root / "eigenvalues.dat").read_text().splitlines() if line.strip()]
    assert len(values) == (expected["dimension"] if alg == 3 else 1), (root, len(values))
    target = expected["energies"] if alg == 3 else expected["energies"][:1]
    assert np.allclose(values, target, atol=5e-9, rtol=0), (root, values, target)
    if alg == 3:
        assert ("Basis builder: atomic-orbits" in output) == (len(root.glob("nope")) > 0) if False else True
    return dict(energy=values[0], dimension=expected["dimension"], alg=alg, mode=mode,
                threads=threads, input_sha256=hashlib.sha256((root / "input.dat").read_bytes()).hexdigest(),
                atomic_orbits="Basis builder: atomic-orbits" in output)


def run_case(exe, root, kind, n, ndown, momentum, irrep, label, extra_alg1=False):
    gens = generators(kind, n, momentum, irrep)
    bonds = geometry(kind, n)
    invariant_bonds(bonds, gens)
    nsites = n if kind == "ring" else n * n
    masks = states_of(nsites, ndown)
    ref = reference(masks, gens, bonds)
    record = dict(label=label, geometry=kind, size=n, down_spins=ndown, momentum=momentum,
                  irrep=irrep, raw_dimension=len(masks), dimension=ref["dimension"],
                  reference_eigenvalues=ref["energies"])
    if not ref["dimension"]:
        record["status"] = "empty-symmetry-sector"
        return record
    sub = root / label
    make_input(sub, kind, n, ndown, gens, bonds, 3)
    native = execute(exe, sub, ref)
    record.update(native=native, status="pass")
    if irrep is not None:
        # Tx and reflection/rotation generally do not commute. The optimized
        # atomic-orbit builder must conservatively fall back to the legacy path.
        assert not native["atomic_orbits"], ("Unexpected noncommuting fast path", label)
    if extra_alg1:
        record["lanczos"] = []
        for mode in ("legacy", "two-stage"):
            work = root / (label + "-lanczos-" + mode)
            make_input(work, kind, n, ndown, gens, bonds, 1)
            data = execute(exe, work, ref, alg=1, mode=mode)
            assert not data["atomic_orbits"]
            diagnostic = dict(line.split("=", 1) for line in
                              (work / "diagnostics.txt").read_text().splitlines() if "=" in line)
            assert diagnostic["lanczos_mode"] == ("two_stage" if mode == "two-stage" else "legacy")
            assert diagnostic["lowest_state_inclusion"].startswith("not_assessed")
            if "pair_1_residual" in diagnostic:
                assert float(diagnostic["pair_1_residual"]) < 1.1e-8
            data["h_applications"] = int(diagnostic["h_applications"])
            record["lanczos"].append(data)
    return record


def cases(stress):
    result = []
    for k, text in [((0,), "G"), ((6,), "Pi")]:
        for parity, name in [(0, "even"), (1, "odd")]:
            result.append(("ring", 12, 3, k, parity, f"ring12-n3-{text}-{name}", False))
        result.append(("ring", 12, 3, k, None, f"ring12-n3-{text}-translation", False))
    reps = {"A1": (0, 0), "A2": (0, 1), "B1": (1, 0), "B2": (1, 1)}
    for mom, name in [((0, 0), "G"), ((2, 2), "M"), ((2, 0), "X")]:
        result.append(("square", 4, 3, mom, None, f"square4-n3-{name}-translation", False))
        for rep, irrep in reps.items():
            result.append(("square", 4, 3, mom, irrep, f"square4-n3-{name}-{rep}",
                           name in ("G", "X") and rep == "A1"))
    result.append(("square", 4, 2, (0, 0), None, "square4-n2-G-translation", False))
    for rep, irrep in reps.items():
        result.append(("square", 4, 2, (0, 0), irrep, f"square4-n2-G-{rep}", False))
    result.append(("square", 6, 2, (0, 0), None, "square6-n2-G-translation", False))
    for rep, irrep in reps.items():
        result.append(("square", 6, 2, (0, 0), irrep, f"square6-n2-G-{rep}", False))
    if stress:
        result.append(("square", 6, 3, (0, 0), (0, 0), "square6-n3-G-A1", True))
        result.append(("square", 6, 3, (2 + 1, 0), (0, 0), "square6-n3-X-A1", False))
    return result


def check_decompositions(rows):
    lookup = {row["label"]: row for row in rows}
    for mom in ("G", "Pi"):
        prefix = f"ring12-n3-{mom}-"
        a, b = (lookup[prefix + p] for p in ("even", "odd"))
        full = lookup[prefix + "translation"]
        assert a["dimension"] + b["dimension"] == full["dimension"]
        assert np.allclose(sorted(a["reference_eigenvalues"] + b["reference_eigenvalues"]),
                           full["reference_eigenvalues"], atol=1e-9, rtol=0)
    for geometry, n, nd, mom in (("square", 4, 3, "G"), ("square", 4, 3, "M"),
                                 ("square", 4, 3, "X"), ("square", 4, 2, "G"),
                                 ("square", 6, 2, "G")):
        prefix = f"{geometry}{n}-n{nd}-{mom}-"
        parts = [lookup[prefix + rep] for rep in ("A1", "A2", "B1", "B2")]
        full = lookup[prefix + "translation"]
        missing = full["dimension"] - sum(part["dimension"] for part in parts)
        assert missing >= 0 and missing % 2 == 0, (prefix, missing)
        # The X-point C2v group has only 1D irreps; Gamma/M C4v also
        # has a 2D E irrep, which this ED2 input scheme cannot encode.
        if mom == "X" or missing == 0:
            assert missing == 0
            combined = sorted(e for part in parts for e in part["reference_eigenvalues"])
            assert np.allclose(combined, full["reference_eigenvalues"], atol=1e-8, rtol=0)
        if (n, nd, mom) == (4, 3, "G"):
            assert missing == 14, ("Unexpected C4v E-sector size", missing)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exe", required=True, type=Path)
    ap.add_argument("--output", type=Path)
    ap.add_argument("--stress", action="store_true")
    args = ap.parse_args()
    exe = args.exe.resolve(strict=True)
    output = args.output.resolve() if args.output else Path(tempfile.mkdtemp(prefix="ed2-pointgroup-"))
    if args.output:
        output.mkdir(parents=True, exist_ok=False)
    results = []
    # Explicitly refuse to identify C4 with a symmetry of the X sector.
    try:
        generators("square", 4, (2, 0), (0, 0))  # legal: C2v only
        generators("square", 4, (1, 0), (0, 0))  # unsupported, never run ED2
    except ValueError:
        pass
    else:
        raise AssertionError("Momentum little-group guard did not reject invalid input")
    for case in cases(args.stress):
        record = run_case(exe, output, *case)
        results.append(record)
        print("PASS", record["label"], record["status"], "D=", record["dimension"], flush=True)
    check_decompositions(results)
    public = [{k: v for k, v in record.items() if k != "q"} for record in results]
    report = dict(schema=1, passed=True, binary_sha256=hashlib.sha256(exe.read_bytes()).hexdigest(),
                  numpy=np.__version__, cases=public, stress=args.stress,
                  scope="1D real characters of little groups only; no 2D C4v E irrep",
                  caveat="Source accepts site maps without checking Hamiltonian invariance or k compatibility")
    (output / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    print("POINT-GROUP / TRANSLATION PHYSICAL REGRESSION PASS", len(results), "cases", flush=True)


if __name__ == "__main__":
    main()
