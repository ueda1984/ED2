#!/usr/bin/env python3
"""Independently compile old ED2 main and shared-row-builder PR, compare H*x bits.

Covers physically real and complex mixed spin couplings, original padded
cache and CSR-release, with/without coefficient-certified row bound.
Both inputs are generated byte identically; compare two full nonreal
complex native H*x outputs (IEEE-754 bits) per source revision.
"""
import argparse
import itertools
import json
from pathlib import Path
from cpc_csr_direct_build_regression import run


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--reference-driver",type=Path,required=True)
    p.add_argument("--candidate-driver",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    p.add_argument("--sizes",default="4,6,8,10")
    p.add_argument("--threads",default="1,4")
    p.add_argument("--models",default="real_xyz,complex_dm,u1_xxz,full_tensor")
    p.add_argument("--timeout",type=int,default=180)
    args=p.parse_args()
    root=args.output.resolve()
    root.mkdir(parents=True,exist_ok=False)
    old=args.reference_driver.resolve(strict=True)
    new=args.candidate_driver.resolve(strict=True)
    sizes=[int(x) for x in args.sizes.split(",")]
    threads=[int(x) for x in args.threads.split(",")]
    models=args.models.split(",")
    assert sizes and all(n in (4,6,8,10) for n in sizes)
    assert threads and all(t>0 for t in threads)
    assert models and all(m in ("real_xyz","complex_dm","u1_xxz","full_tensor")
                          for m in models)
    count=0
    for n,model,t,mode,bounded in itertools.product(
            sizes,models,threads,("padded","release"),(False,True)):
        arguments=(n,model,t,mode,bounded,args.timeout)
        a=run(old,root/"old-{}-{}-t{}-{}-{}".format(
            n,model,t,mode,int(bounded)),*arguments)
        b=run(new,root/"new-{}-{}-t{}-{}-{}".format(
            n,model,t,mode,int(bounded)),*arguments)
        assert a["input"]==b["input"],(
            "Reference and refactored ED2 inputs differ",arguments)
        assert a["hash"]==b["hash"],(
            "Refactoring changed complete native complex output bits",arguments)
        count+=1
        print("CSR_DIRECT_OLD_MAIN_BITWISE_PASS n={} model={} t={} mode={} bound={}"
              .format(n,model,t,mode,int(bounded)),flush=True)
    (root/"summary.json").write_text(json.dumps({
        "status":"PASS","exact_pairs":count,
        "old_binary":str(old),"new_binary":str(new)},indent=2)+"\n")
    print("CSR_DIRECT_OLD_MAIN_CROSSBUILD_PASS exact_pairs={}".format(count),
          flush=True)


if __name__=="__main__":
    main()
