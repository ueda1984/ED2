#!/usr/bin/env python3
"""Reduce Phase 1-D raw runs to reviewable data; never convert failures to passes."""
import argparse
import collections
import csv
import hashlib
import json
from pathlib import Path
import statistics


def read(path):return json.loads(path.read_text())

def write(path,value):path.write_text(json.dumps(value,indent=2,allow_nan=False)+'\n')

def csv_rows(path,rows):
    keys=list(dict.fromkeys(k for row in rows for k in row))
    with path.open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=keys,lineterminator='\n');w.writeheader()
        for row in rows:w.writerow({k:json.dumps(v,separators=(',',':')) if isinstance(v,(dict,list)) else v for k,v in row.items()})


def strip_log(src,dst):
    dst.write_text('\n'.join(s.rstrip() for s in src.read_text().splitlines()).rstrip()+'\n')


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--raw',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();raw=a.raw.resolve();out=a.output.resolve();out.mkdir(parents=True,exist_ok=False)
    summary={'stress':{},'regressions':{},'acceptance':{}};rng={};selected=[]
    for profile in ['default','o2','bounds','gnu13']:
        d=read(raw/f'stress-{profile}/report.json');rows=d['cases'];short=[]
        for r in rows:
            z=dict(r);states=z.pop('rng_state',[]);key=f"{z['seed']}-omp{z['threads']}"
            if key in rng:assert rng[key]==states
            rng[key]=states;z['rng_key']=key;short.append(z)
        csv_rows(out/f'{profile}-stress.csv',short)
        summary['stress'][profile]={'counts':d['counts'],'driver_sha256':d['driver_sha256'],'harness_sha256':d['harness_sha256'],'numpy':d['numpy'],'accepted_by_alg_tol':{},'nonconvergence_with_accurate_last_alg2_candidate':sum(r.get('last_candidate_meets_strict_energy_and_residual',False) for r in rows)}
        for alg in [1,2]:
            for tol in [1e-6,1e-12,1e-20]:
                rs=[r for r in rows if r['alg']==alg and r['tol']==tol and r['family'] not in ['parameter-grid','excluded-ground','weak-ground-overlap']]
                ok=[r for r in rs if r['solver_status']==0]
                summary['stress'][profile]['accepted_by_alg_tol'][f'alg{alg}-tol{tol}']={'counts':dict(collections.Counter(r['classification'] for r in rs)),'max_normalized_residual':max((max(r['normalized_residuals']) for r in ok),default=None),'max_ground_eigenvalue_error':max((max(r['eigenvalue_errors']) for r in ok),default=None),'max_requested_space_leakage':max((r['requested_space_leakage'] for r in ok),default=None)}
        if profile=='o2':
            ids=['0015-omp1','0090-omp1','0129-omp1','0207-omp1','0208-omp1']
            selected=[r for r in rows if r['id'] in ids]
        baseline=read(raw/f'{profile}-independent/report.json');sparse=read(raw/f'{profile}-sparse/report.json');stability=read(raw/f'{profile}-stability/report.json');cli=read(raw/f'{profile}-stability-cli/report.json');hist=read(raw/f'{profile}-historical.json')
        summary['regressions'][profile]={'independent':{'passed':baseline['passed'],'failed':baseline['failed']},'sparse_cli':sparse['cli_counts'],'operators':sparse['operator_counts'],'permutations':sparse['permutation_counts'],'kernel_stability':{'passed':stability['passed'],'failed':stability['failed']},'cli_stability':{'passed':cli['passed'],'failed':cli['failed']},'historical':{'passed':hist['passed'],'failed':hist['failed']},'extended':{'passed':(raw/f'{profile}-extended.log').read_text().count('PASS: test_ex')},'lapack_pass_11':'PASS: 11 interface/error-path checks' in (raw/f'{profile}-lapack.log').read_text(),'executable_sha256':baseline['executable_sha256']}
        # Keep any failure details explicitly, including unchanged regression failures.
        failures=[dict(suite='independent',**r) for r in baseline['cases'] if r['status']!='passed']
        failures += [dict(suite='sparse-'+k,**r) for k in ['cli','operators','permutations'] for r in sparse[k] if r['status']!='passed']
        if failures:write(out/f'{profile}-regression-failures.json',failures)
        write(out/f'{profile}-historical.json',hist)
        for kind in ['autoreconf','configure','build','lapack','stability','sparse','standard','extended','historical','independent']:
            strip_log(raw/f'{profile}-{kind}.log',out/f'{profile}-{kind}.log')
    write(out/'rng-states.json',rng);write(out/'selected-stress-cases.json',selected)
    d=read(raw/'acceptance-final/report.json');summary['acceptance']={k:v for k,v in d.items() if k!='cases'}
    csv_rows(out/'acceptance.csv',[{k:v for k,v in r.items() if k not in ['input_sha256','rng_state']} for r in d['cases']])
    # The fixture input is generated by the unchanged sparse-field preparation;
    # per-run seed/thread plus the probe's documented mapping reconstructs state.
    write(out/'acceptance-input-provenance.json',[{k:r[k] for k in ['id','input_sha256']} for r in d['cases'][:1]])
    d=read(raw/'benchmarks/report.json');bench=d.pop('cases');write(out/'benchmark-provenance.json',d)
    csv_rows(out/'benchmarks.csv',[{k:v for k,v in r.items() if k not in ['rng_state','input_sha256']} for r in bench])
    write(out/'benchmark-input-hashes.json',{r['id']:r['input_sha256'] for r in bench})
    groups={}
    for r in bench:groups.setdefault((r['name'],r['label'],r['threads']),[]).append(r)
    aggregates=[]
    for (name,label,threads),rs in groups.items():
        row=dict(name=name,label=label,threads=threads,runs=len(rs),classifications=dict(collections.Counter(r['classification'] for r in rs)))
        for metric in ['wall_seconds','compute_seconds','peak_rss_kib','h_applications','restart_cycles']:
            vals=[r[metric] for r in rs if metric in r]
            if vals:row[metric]={'median':statistics.median(vals),'min':min(vals),'max':max(vals)}
        row['max_residual']=max((max(r['residual_norms']) for r in rs if 'residual_norms' in r),default=None)
        aggregates.append(row)
    write(out/'benchmark-aggregates.json',aggregates)
    summary['benchmarks']={'runs':len(bench),'counts':dict(collections.Counter(r['classification'] for r in bench))}
    for label in ['phase1b','phase1c']:
        strip_log(raw/f'benchmarks/{label}-build.log',out/f'benchmark-{label}-build.log')
        patch=(raw/f'benchmarks/{label}-instrumentation.patch').read_text()
        write(out/f'benchmark-{label}-instrumentation.json',{'diff_lines':patch.splitlines(keepends=True),'sha256':hashlib.sha256(patch.encode()).hexdigest()})
    write(out/'replay-check.json',read(raw/'replay-check.json'))
    for f in ['regressions.json','regressions-gnu13.json']:write(out/f,read(raw/f))
    write(out/'summary.json',summary)
    print('Wrote',len(list(out.iterdir())),'files;',sum(p.stat().st_size for p in out.iterdir()),'bytes')
    return 0


if __name__=='__main__':raise SystemExit(main())
